-- Архив: команда «Архив» на iPhone загружает старые фото, от самых старых к новым.
-- Здесь — докуда она дошла. Отдельно от ключа: новый ключ не сбрасывает прогресс архива.
CREATE TABLE archive_progress (
  user_id INTEGER PRIMARY KEY,
  cursor INTEGER,                    -- дата съёмки последнего фото, которое прошло через архив, миллисекунды
  used INTEGER                       -- когда команда «Архив» запускалась в последний раз
);
-- Поиск фото по дате съёмки: архив не загружает второй раз то, что уже загружено другим путём.
CREATE INDEX photos_by_taken ON photos (user_id, taken);
